using System.Linq;
using System.Threading.Tasks;
using Xunit;

namespace xUnitTest;

public sealed class ConfigurationTests
{
    [Theory]
    [InlineData("max_lines", "0")]
    [InlineData("max_lines", "-1")]
    [InlineData("max_lines", "2147483648")]
    [InlineData("max_lines", "+50")]
    [InlineData("max_lines", "1,000")]
    [InlineData("max_lines", "1.5")]
    [InlineData("max_lines", "")]
    [InlineData("max_parameters", "-1")]
    [InlineData("max_parameters", "no")]
    [InlineData("max_out_parameters", "-1")]
    [InlineData("allow_exempt", "yes")]
    public async Task InvalidOptionsProduceAnErrorWithoutFallback(string key, string value)
    {
        var diagnostic = Assert.Single(await AnalyzerTest.Run("class C {}", AnalyzerTest.Options((key, value))));
        Assert.Equal("LEASH0004", diagnostic.Id);
        Assert.Contains("leash." + key, diagnostic.GetMessage());
        Assert.Contains("Expected", diagnostic.GetMessage());
        Assert.Equal(0, diagnostic.Location.SourceSpan.Start);
    }

    [Fact]
    public async Task InvalidNumericOptionSkipsOnlyItsDependentRule()
    {
        var diagnostics = await AnalyzerTest.Run("class C { void M(int a, int b, out int c, out int d) { F(); G(); } }",
            AnalyzerTest.Options(("max_lines", "bad"), ("max_parameters", "1")));
        Assert.Equal(new[] { "LEASH0004", "LEASH0002", "LEASH0003" }, diagnostics.Select(d => d.Id));
    }

    [Fact]
    public async Task ValidBoundaryValuesWhitespaceAndUnknownKeysAreAccepted()
    {
        var options = AnalyzerTest.Options(("max_lines", " 2147483647 "), ("max_parameters", " 0 "),
            ("max_out_parameters", "0"), ("allow_exempt", " TrUe "), ("unknown", "bad"));
        Assert.Empty(await AnalyzerTest.Run("class C { void M() {} }", options));
    }

    [Fact]
    public async Task ReportsEachInvalidEffectiveOptionOncePerFile()
    {
        var trees = new[] { AnalyzerTest.Parse("class A { void M() {} void N() {} }", "A.cs"), AnalyzerTest.Parse("class B {}", "B.cs") };
        var diagnostics = await AnalyzerTest.RunTrees(trees, AnalyzerTest.Options(("max_lines", "bad"), ("max_parameters", "bad")));
        Assert.Equal(4, diagnostics.Length);
        Assert.All(diagnostics, d => Assert.Equal("LEASH0004", d.Id));
    }

    [Fact]
    public async Task EscapesNewLinesInInvalidValues()
    {
        var diagnostic = Assert.Single(await AnalyzerTest.Run("", AnalyzerTest.Options(("max_lines", "a\r\nb"))));
        Assert.Contains("a\\r\\nb", diagnostic.GetMessage());
        Assert.DoesNotContain('\n', diagnostic.GetMessage());
    }

    [Theory]
    [InlineData(0x0085, "\\u0085")]
    [InlineData(0x2028, "\\u2028")]
    [InlineData(0x2029, "\\u2029")]
    public async Task EscapesUnicodeLineBreaksInInvalidValues(int lineBreak, string escaped)
    {
        var value = "a" + (char)lineBreak + "b";
        var diagnostic = Assert.Single(await AnalyzerTest.Run("", AnalyzerTest.Options(("max_lines", value))));
        Assert.Contains("'a" + escaped + "b'", diagnostic.GetMessage());
        Assert.DoesNotContain((char)lineBreak, diagnostic.GetMessage());
    }

    [Fact]
    public async Task InvalidBooleanDoesNotGrantExemptionsOrDisableOtherChecks()
    {
        var diagnostics = await AnalyzerTest.Run("class C { [LeashExempt(\"reason\")] void M(int x) {} }",
            AnalyzerTest.Options(("allow_exempt", "bad"), ("max_parameters", "0")));
        Assert.Equal(new[] { "LEASH0004", "LEASH0002" }, diagnostics.Select(d => d.Id));
    }

    [Theory]
    [InlineData("Test.g.cs", "class C { void M(int x) {} }")]
    [InlineData("Test.designer.cs", "class C { void M(int x) {} }")]
    [InlineData("Test.cs", "// <auto-generated/>\nclass C { void M(int x) {} }")]
    public async Task RoslynGeneratedFilesAreSkipped(string path, string source)
    {
        Assert.Empty(await AnalyzerTest.Run(source, AnalyzerTest.Options(("max_parameters", "0"), ("max_lines", "bad")), path));
    }

    [Fact]
    public async Task HostGeneratedCodeClassificationIsRespected() =>
        Assert.Empty(await AnalyzerTest.Run("class C { void M(int x) {} }", AnalyzerTest.Options(("max_parameters", "0")), generated: true));

    [Fact]
    public async Task ExplicitNonGeneratedSettingOverridesGeneratedFileName()
    {
        var options = AnalyzerTest.Options(("max_parameters", "0"));
        options["generated_code"] = "false";
        Assert.Single(await AnalyzerTest.Run("class C { void M(int x) {} }", options, "Test.g.cs"));
    }

    [Theory]
    [InlineData("")]
    [InlineData("missing/folder/HandWritten.cs")]
    public async Task VirtualAndMissingPathsAreStillAnalyzed(string path) =>
        Assert.Single(await AnalyzerTest.Run("class C { void M(int x) {} }", AnalyzerTest.Options(("max_parameters", "0")), path));

    [Fact]
    public async Task ConcurrentTreesHaveIsolatedCounters()
    {
        var trees = Enumerable.Range(0, 32).Select(i => AnalyzerTest.Parse($"class C{i} {{ void M(int x) {{ F(); G(); }} }}", $"{i}.cs")).ToArray();
        var diagnostics = await AnalyzerTest.RunTrees(trees, AnalyzerTest.Options(("max_lines", "1"), ("max_parameters", "0")));
        Assert.Equal(64, diagnostics.Length);
        Assert.Equal(32, diagnostics.Count(d => d.Id == "LEASH0001"));
        Assert.Equal(32, diagnostics.Count(d => d.Id == "LEASH0002"));
    }
}
